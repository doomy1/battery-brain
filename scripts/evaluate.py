"""Benchmark the estimators and the chargers; write docs/results.md and plots.

    python scripts/evaluate.py
"""
import json
import math
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from batterybrain.sim import ChargeRace, EstimationSession


def estimation_run(profile, ambient, seed=11, hours=1.5, init_error=0.2, skip_s=900):
    """SOC RMSE [% SOC] of each estimator after a wrong initial guess."""
    s = EstimationSession(profile, ambient_c=ambient, soc0=0.85, seed=seed)
    s.scramble(init_error)
    s.step(skip_s)            # allow convergence, then score
    s.reset_stats()
    out = s.step(int(hours * 3600) - skip_s)
    return {k: 100.0 * v for k, v in out["rmse"].items()}


def race_run(ambient, t_max=45.0, i_max=15.0):
    race = ChargeRace(ambient_c=ambient, t_max=t_max, i_max=i_max)
    log = {"t": [], "table": {"soc": [], "current": [], "voltage": [], "temp": []},
           "mpc": {"soc": [], "current": [], "voltage": [], "temp": []}}
    while not race.finished and race.t < 3 * 3600:
        out = race.step(60)
        log["t"] += out["t"]
        for lane in ("table", "mpc"):
            for key in log[lane]:
                log[lane][key] += out[lane][key]
    return out["summary"], log


def main():
    lines = ["# Results", "", "Generated by `python scripts/evaluate.py`. All numbers are from simulation.", ""]

    lines += ["## State of charge estimation", "",
              "RMS error in % SOC over 75 minutes, after starting every estimator 20 % wrong",
              "and allowing 15 minutes to converge.", "",
              "| Profile | Ambient | Coulomb counting | EKF | EKF + neural net |",
              "|---|---|---|---|---|"]
    est_rows = []
    for profile in ("drive", "home"):
        for ambient in (0, 10, 25, 40):
            r = estimation_run(profile, ambient)
            est_rows.append((profile, ambient, r))
            lines.append(f"| {profile} | {ambient} degC | {r['cc']:.1f} | {r['ekf']:.2f} | {r['nn']:.2f} |")
            print(lines[-1])
    mean = {k: float(np.mean([r[k] for _, _, r in est_rows])) for k in ("cc", "ekf", "nn")}
    lines.append(f"| **mean** | | **{mean['cc']:.1f}** | **{mean['ekf']:.2f}** | **{mean['nn']:.2f}** |")
    print(lines[-1])

    lines += ["", "## Fast charging, 10 % to 80 %", "",
              "Limits: 15 A (3C), 4.2 V, 45 degC. Peak values are the true cell values.", "",
              "| Ambient | Table charger time | MPC time | MPC faster by | Table peak T / V | MPC peak T / V |",
              "|---|---|---|---|---|---|"]
    logs = {}
    for ambient in (10, 25, 35):
        summary, log = race_run(ambient)
        logs[ambient] = log
        tt, tm = summary["table"]["finish_time"], summary["mpc"]["finish_time"]
        fmt = lambda s: "did not finish" if s is None else f"{int(s // 60)}:{int(s % 60):02d}"
        gain = "" if not (tt and tm) else f"{100.0 * (tt - tm) / tt:.0f} %"
        lines.append(f"| {ambient} degC | {fmt(tt)} | {fmt(tm)} | {gain} | "
                     f"{summary['table']['peak_temp']:.1f} degC / {summary['table']['peak_volt']:.3f} V | "
                     f"{summary['mpc']['peak_temp']:.1f} degC / {summary['mpc']['peak_volt']:.3f} V |")
        print(lines[-1])

    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "results.md").write_text("\n".join(lines) + "\n")

    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("matplotlib not installed, skipping plots")
        return

    log = logs[25]
    t = np.array(log["t"]) / 60.0
    fig, axes = plt.subplots(4, 1, figsize=(8, 9), sharex=True)
    for lane, color, label in (("table", "#c2410c", "Table charger (CC-CV + derating)"),
                               ("mpc", "#0f766e", "MPC")):
        axes[0].plot(t, 100 * np.array(log[lane]["soc"]), color=color, label=label)
        axes[1].plot(t, log[lane]["current"], color=color)
        axes[2].plot(t, log[lane]["voltage"], color=color)
        axes[3].plot(t, log[lane]["temp"], color=color)
    axes[2].axhline(4.2, color="gray", ls="--", lw=1)
    axes[3].axhline(45.0, color="gray", ls="--", lw=1)
    for ax, label in zip(axes, ("SOC [%]", "Charge current [A]", "Voltage [V]", "Temperature [degC]")):
        ax.set_ylabel(label)
        ax.grid(alpha=0.3)
    axes[0].legend()
    axes[3].set_xlabel("Time [min]")
    fig.suptitle("Fast charge 10 % to 80 % at 25 degC ambient")
    fig.tight_layout()
    fig.savefig(ROOT / "docs" / "fast_charge.png", dpi=130)

    hist = json.loads((ROOT / "docs" / "training_history.json").read_text())
    fig, ax = plt.subplots(figsize=(7, 3.5))
    h = np.array(hist["rmse_mv"])
    ax.plot(h[:, 0], label="train")
    ax.plot(h[:, 1], label="validation (unseen temperatures)")
    ax.axhline(hist["nominal_val_rmse_mv"], color="gray", ls="--", label="physics model alone")
    ax.set_yscale("log")
    ax.set_xlabel("Epoch")
    ax.set_ylabel("Voltage error [mV rms]")
    ax.grid(alpha=0.3, which="both")
    ax.legend()
    fig.tight_layout()
    fig.savefig(ROOT / "docs" / "training.png", dpi=130)
    print("wrote docs/results.md and plots")


if __name__ == "__main__":
    main()
